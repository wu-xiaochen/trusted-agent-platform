#!/usr/bin/env bash
# TP-02 reproducible infrastructure bootstrap.
# Brings up platform Postgres, external read-only source Postgres and the Dex
# OIDC issuer on loopback host ports (see environment.md). Generates only
# git-ignored local/ state. Safe to re-run.
set -euo pipefail

SPIKE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
REPO_ROOT="$(cd "$SPIKE_DIR/../.." && pwd)"
LOCAL_DIR="$SPIKE_DIR/local"
BCRYPT_TOOL="$REPO_ROOT/work/bcrypt-tool"

mkdir -p "$LOCAL_DIR/dex"

# 1. Local synthetic environment -------------------------------------------
if [[ ! -f "$LOCAL_DIR/.env" ]]; then
  cp "$SPIKE_DIR/local.env.example" "$LOCAL_DIR/.env"
  echo "wrote $LOCAL_DIR/.env from local.env.example"
fi
# shellcheck disable=SC1091
source "$LOCAL_DIR/.env"

# 2. ObjectStack host environment (random secrets, never committed) ----------
if [[ ! -f "$LOCAL_DIR/app.env" ]]; then
  AUTH_SECRET="$(openssl rand -hex 32)"
  SECRET_KEY="$(openssl rand -hex 32)"
  cat > "$LOCAL_DIR/app.env" <<EOF
# Generated by scripts/bootstrap-infra.sh — local disposable secrets, git-ignored.
NODE_ENV=production
OS_PORT=$TP02_APP_PORT
OS_DATABASE_URL=postgres://$PLATFORM_PG_USER:$PLATFORM_PG_PASSWORD@localhost:55432/$PLATFORM_PG_DB
OS_AUTH_SECRET=$AUTH_SECRET
OS_SECRET_KEY=$SECRET_KEY
OS_AUTH_URL=http://localhost:$TP02_APP_PORT
OS_TRUSTED_ORIGINS=http://localhost:$TP02_APP_PORT
OS_AUTH_SIGNUP_ENABLED=true
OS_EMAIL_PROVIDER=log
EOF
  echo "wrote $LOCAL_DIR/app.env (synthetic secrets generated)"
fi

# 3. Dex config with two synthetic users and one static OIDC client ----------
gen_hash() { node -e "console.log(require('$BCRYPT_TOOL/node_modules/bcryptjs').hashSync(process.argv[1],10))" "$1"; }
HASH_PLANNER="$(gen_hash 'planner-synthetic-pw')"
HASH_TECH="$(gen_hash 'technician-synthetic-pw')"
cat > "$LOCAL_DIR/dex/config.docker.yaml" <<EOF
# Generated — disposable local test IdP, git-ignored.
issuer: http://localhost:5556
storage:
  type: sqlite3
  config: { file: /var/dex/dex.db }
web: { http: 0.0.0.0:5556 }
logger: { level: info }
oauth2:
  responseTypes: ["code"]
  skipApprovalScreen: true
staticClients:
  - id: tp02-qual
    redirectURIs:
      - http://localhost:$TP02_APP_PORT/api/v1/auth/callback/dex
    name: TP-02 Qualification Host
    public: true
enablePasswordDB: true
staticPasswords:
  - email: planner@tp02.local
    username: planner
    hash: "$HASH_PLANNER"
    userID: id-planner-0001
  - email: technician@tp02.local
    username: technician
    hash: "$HASH_TECH"
    userID: id-technician-0002
EOF
echo "wrote $LOCAL_DIR/dex/config.docker.yaml (2 synthetic users)"

# 4. Start containers and wait for health -------------------------------------
docker compose -f "$SPIKE_DIR/infra/compose.yml" --env-file "$LOCAL_DIR/.env" up -d db source-db dex

echo "waiting for healthy services..."
for i in $(seq 1 60); do
  db_health="$(docker inspect --format '{{.State.Health.Status}}' tp02-qual-db-1 2>/dev/null || true)"
  src_health="$(docker inspect --format '{{.State.Health.Status}}' tp02-qual-source-db-1 2>/dev/null || true)"
  if [[ "$db_health" == healthy && "$src_health" == healthy ]]; then break; fi
  sleep 2
done
for i in $(seq 1 30); do
  if curl -fsS http://localhost:5556/healthz >/dev/null 2>&1; then break; fi
  sleep 2
done

docker compose -f "$SPIKE_DIR/infra/compose.yml" --env-file "$LOCAL_DIR/.env" ps
echo "Dex discovery: $(curl -fsS http://localhost:5556/.well-known/openid-configuration | node -e 'let d="";process.stdin.on("data",c=>d+=c).on("end",()=>{const j=JSON.parse(d);console.log(j.issuer)})')"
echo "infra ready"
